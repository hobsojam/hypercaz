import { validatePuzzle, type Direction, type Puzzle } from './sim.ts';

type Shape = readonly [direction: Direction, path: readonly (readonly [x: number, y: number])[]];
function puzzle(id: number, name: string, lesson: string, size: number, shapes: readonly Shape[]): Puzzle {
  return validatePuzzle({ id, name, lesson, size, arrows: shapes.map(([direction, path], i) => ({ id: i + 1, direction, path: path.map(([x, y]) => ({ x, y })) })) });
}

